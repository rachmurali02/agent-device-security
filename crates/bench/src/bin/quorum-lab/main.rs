//! `quorum-lab`: experiments on the quorum HSM.
//!
//! - `quorum-lab load`: performance under load (concurrency, noisy
//!   neighbours, soak, kill -9 in the middle of traffic)
//! - `quorum-lab attacks`: more attack vectors, each one carried out
//! - `quorum-lab all`: both
//!
//! Options: `--out <report.md>`, `--data <raw.tsv>`, `--seconds <per level>`,
//! `--max-clients <n>`, `--soak <seconds>`, `--crash-rounds <n>`.
//! Needs the release build of `quorum-emulator` next to it
//! (`cargo build --release`). Exits 1 if any check fails or any attack
//! turns out differently from what is expected.

mod attacks;
mod common;
mod load;

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::ExitCode;

fn flag(args: &[String], name: &str) -> Option<String> {
    args.iter()
        .position(|a| a == name)
        .and_then(|i| args.get(i + 1).cloned())
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let what = args.first().map(String::as_str).unwrap_or("all");
    if !matches!(what, "load" | "attacks" | "all") {
        eprintln!(
            "usage: quorum-lab (load | attacks | all) [--out report.md] [--data raw.tsv] [--seconds 3] [--max-clients 64] [--soak 30] [--crash-rounds 25]"
        );
        return ExitCode::FAILURE;
    }
    let num = |name: &str, default: f64| {
        flag(&args, name)
            .and_then(|v| v.parse().ok())
            .unwrap_or(default)
    };
    let settings = load::Settings {
        seconds: num("--seconds", 3.0),
        max_clients: num("--max-clients", 64.0) as usize,
        soak_seconds: num("--soak", 30.0),
        crash_rounds: num("--crash-rounds", 25.0) as usize,
    };
    let dir = std::env::temp_dir().join(format!("quorum-lab-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("work dir");

    let mut out = String::new();
    let mut data = String::new();
    writeln!(out, "# quorum-lab results\n").unwrap();
    writeln!(
        out,
        "Machine: {} ({} cores). Generated by `quorum-lab {what}`; see docs/EXPERIMENTS.md for what the numbers mean.\n",
        cpu_name(),
        std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1)
    )
    .unwrap();
    let mut ok = true;
    if what != "attacks" {
        writeln!(out, "# Performance under load\n").unwrap();
        ok &= load::run(&dir, &settings, &mut out, &mut data);
    }
    if what != "load" {
        writeln!(out, "# Attack vectors\n").unwrap();
        ok &= attacks::run(&dir, &mut out, &mut data);
    }
    let _ = std::fs::remove_dir_all(&dir);

    match flag(&args, "--out") {
        Some(p) => std::fs::write(PathBuf::from(&p), &out).expect("write report"),
        None => print!("{out}"),
    }
    if let Some(p) = flag(&args, "--data") {
        std::fs::write(PathBuf::from(&p), &data).expect("write data");
    }
    if ok {
        ExitCode::SUCCESS
    } else {
        eprintln!("quorum-lab: some checks FAILED (see the report)");
        ExitCode::FAILURE
    }
}

fn cpu_name() -> String {
    std::fs::read_to_string("/proc/cpuinfo")
        .ok()
        .and_then(|s| {
            s.lines()
                .find(|l| l.starts_with("model name"))
                .and_then(|l| l.split(':').nth(1))
                .map(|s| s.trim().to_string())
        })
        .unwrap_or_else(|| "unknown CPU".into())
}
