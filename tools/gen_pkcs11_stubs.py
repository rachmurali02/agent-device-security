#!/usr/bin/env python3
"""Generates crates/pkcs11/src/function_list.rs from cryptoki-sys bindings.

Every PKCS#11 function we do not implement gets a stub returning
CKR_FUNCTION_NOT_SUPPORTED, with its exact C signature, so callers never hit
a NULL function pointer.

Usage:
  tools/gen_pkcs11_stubs.py <cryptoki-sys x86_64-unknown-linux-gnu.rs> \
    > crates/pkcs11/src/function_list.rs && cargo fmt
"""
import re
import sys

IMPLEMENTED = {
    "C_Initialize", "C_Finalize", "C_GetInfo", "C_GetFunctionList",
    "C_GetSlotList", "C_GetSlotInfo", "C_GetTokenInfo",
    "C_GetMechanismList", "C_GetMechanismInfo",
    "C_OpenSession", "C_CloseSession", "C_CloseAllSessions", "C_GetSessionInfo",
    "C_Login", "C_Logout",
    "C_DestroyObject", "C_GetAttributeValue",
    "C_FindObjectsInit", "C_FindObjects", "C_FindObjectsFinal",
    "C_SignInit", "C_Sign", "C_VerifyInit", "C_Verify",
    "C_GenerateKeyPair",
}

src = open(sys.argv[1]).read()
body = re.search(r"pub struct CK_FUNCTION_LIST \{(.*?)\n\}", src, re.S).group(1)
fields = re.findall(r"pub (C_\w+): CK_C_\w+,", body)

out = [
    "// @generated by tools/gen_pkcs11_stubs.py. Do not edit by hand.",
    "#![allow(non_snake_case, clippy::missing_safety_doc)]",
    "",
    "use cryptoki_sys::*;",
    "",
    "use crate::api;",
    "",
]
for name in fields:
    if name in IMPLEMENTED:
        continue
    sig = re.search(
        r"pub type CK_%s =\s*::std::option::Option<\s*unsafe extern \"C\" fn\((.*?)\) -> CK_RV,?\s*>;"
        % name, src, re.S).group(1)
    args = ", ".join("_" + a.strip() for a in sig.split(",") if a.strip())
    args = args.replace("::std::os::raw::", "std::os::raw::")
    out.append(f'unsafe extern "C" fn {name}({args}) -> CK_RV {{\n    CKR_FUNCTION_NOT_SUPPORTED\n}}\n')

out.append("pub static FUNCTION_LIST: CK_FUNCTION_LIST = CK_FUNCTION_LIST {")
out.append("    version: CK_VERSION { major: 2, minor: 40 },")
for name in fields:
    target = f"api::{name}" if name in IMPLEMENTED else name
    out.append(f"    {name}: Some({target}),")
out.append("};")
print("\n".join(out))
